export function translate(key: string, lang: Lang, vars?: Record<string, string>): string {
  const entry = T[key]
  let text = entry ? entry[lang] : key
  if (vars) {
    for (const [k, v] of Object.entries(vars)) text = text.replace(`{${k}}`, v)
  }
  return text
}
